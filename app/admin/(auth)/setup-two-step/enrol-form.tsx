"use client";

import { useActionState } from "react";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { FormAlert, SubmitButton } from "@/components/cms/form-bits";
import { confirmEnrolment, startEnrolment, type EnrolState } from "@/lib/auth/actions";

/** Step 1: start setup (creates a fresh QR code on the server). */
export function EnrolForm({ next }: { next: string }) {
  const [started, start] = useActionState<EnrolState, FormData>(startEnrolment, {});

  if (started.factorId && started.secret) {
    return <ConfirmStep enrolment={started} next={next} />;
  }

  return (
    <form action={start} className="space-y-5">
      <FormAlert error={started.error} />
      <ol className="list-decimal space-y-2 pl-5 text-sm leading-relaxed">
        <li>
          Install an authenticator app on your phone, for example <strong>Google Authenticator</strong> or{" "}
          <strong>Microsoft Authenticator</strong>.
        </li>
        <li>Press the button below to show your personal QR code.</li>
      </ol>
      <SubmitButton pendingText="Preparing…">Show my QR code</SubmitButton>
    </form>
  );
}

/** Step 2: scan the QR code, then prove it worked with a code. */
function ConfirmStep({ enrolment, next }: { enrolment: EnrolState; next: string }) {
  const [state, action] = useActionState<EnrolState, FormData>(confirmEnrolment, enrolment);
  const groupedSecret = enrolment.secret?.match(/.{1,4}/g)?.join(" ");

  return (
    <form action={action} className="space-y-5" noValidate>
      <input type="hidden" name="factorId" value={enrolment.factorId} />
      <input type="hidden" name="next" value={next} />

      {enrolment.qrCode ? (
        <>
          <p className="text-sm leading-relaxed">
            In the app, choose <strong>Add account</strong> (or <strong>+</strong>), then{" "}
            <strong>Scan a QR code</strong>, and point your camera at this code:
          </p>
          <div className="flex justify-center border border-border bg-white p-4">
            {/* The QR code is generated by Supabase as an image; it never leaves this page. */}
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={enrolment.qrCode} alt="QR code for your authenticator app" width={184} height={184} />
          </div>
        </>
      ) : null}
      <details className="text-sm" open={!enrolment.qrCode}>
        <summary className="cursor-pointer text-indigo">Can&apos;t scan it? Enter a setup key instead</summary>
        <p className="mt-2 text-muted-foreground">
          Choose <strong>Enter a setup key</strong> in the app, name it <strong>VECTIS CMS</strong>, and type:
        </p>
        <p className="mt-2 border border-border bg-muted px-3 py-2 text-center font-mono text-sm break-all select-all">
          {groupedSecret}
        </p>
      </details>

      <FormAlert error={state.error} />
      <div className="space-y-2">
        <Label htmlFor="code">Enter the 6-digit code the app now shows</Label>
        <Input
          id="code"
          name="code"
          inputMode="numeric"
          autoComplete="one-time-code"
          pattern="\d{6}"
          maxLength={6}
          required
          className="text-center font-mono text-lg tracking-[0.4em]"
        />
      </div>
      <SubmitButton pendingText="Checking…">Finish setup</SubmitButton>
    </form>
  );
}
